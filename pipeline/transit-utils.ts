/**
 * One frequencies.txt row, in minutes from midnight.
 */
export interface FrequencyWindow {
    start: number;
    end: number;
    headwayMinutes: number;
}

/**
 * Some exporters (TransLoc: Coast RTA, Waco, Winter Park) write one
 * frequencies.txt row per scheduled trip: the window is that trip's own run
 * time and headway_secs is a meaningless value below it, so the literal
 * expansion (departures every headway while start <= t < end_time) invents
 * extra departures inside the window (#702, #706).
 *
 * A row is that single trip when the literal expansion gives no more than
 * SINGLE_TRIP_WINDOW_MAX_DEPARTURES and either
 * - the window equals the trip's stop_times span within
 *   SINGLE_TRIP_WINDOW_SPAN_TOLERANCE_MIN (#702), or
 * - the trip has only this one frequencies.txt row and the window runs at most
 *   SINGLE_TRIP_WINDOW_LAYOVER_MIN longer than the trip (#706: Winter Park
 *   TL-42's 90-minute windows over 85-minute runs).
 * The layover allowance is limited to single-row trips because a genuine
 * template trip with several rows can end on a short block of real service
 * (uga 922721: 17:30-18:00 every 15 over a 25-minute run).
 *
 * Shared by route-level (transit-phase1) and stop-level (process-core)
 * expansion so the two always agree.
 */
export const SINGLE_TRIP_WINDOW_SPAN_TOLERANCE_MIN = 1;
export const SINGLE_TRIP_WINDOW_LAYOVER_MIN = 5;
export const SINGLE_TRIP_WINDOW_MAX_DEPARTURES = 3;

export function isSingleTripFrequencyWindow(
    windowMinutes: number,
    generatedDepartures: number,
    tripSpanMinutes: number | undefined,
    tripFrequencyRowCount?: number,
): boolean {
    if (tripSpanMinutes === undefined || !Number.isFinite(tripSpanMinutes) || !Number.isFinite(windowMinutes)) return false;
    if (generatedDepartures <= 1 || generatedDepartures > SINGLE_TRIP_WINDOW_MAX_DEPARTURES) return false;
    const excess = windowMinutes - tripSpanMinutes;
    if (Math.abs(excess) <= SINGLE_TRIP_WINDOW_SPAN_TOLERANCE_MIN) return true;
    return tripFrequencyRowCount === 1 && excess > 0 && excess <= SINGLE_TRIP_WINDOW_LAYOVER_MIN;
}

/**
 * Departure times (minutes from midnight) generated by one frequencies.txt
 * row: every headway while `generated < end`, or only the window start when
 * the row is one scheduled trip (isSingleTripFrequencyWindow).
 */
export function expandFrequencyWindow(
    window: FrequencyWindow,
    tripSpanMinutes?: number,
    tripFrequencyRowCount?: number,
): number[] {
    const { start, end, headwayMinutes } = window;
    if (!Number.isFinite(start) || !Number.isFinite(end) || !Number.isFinite(headwayMinutes) || headwayMinutes <= 0 || end <= start) return [];
    const departures: number[] = [];
    for (let generated = start; generated < end; generated += headwayMinutes) departures.push(generated);
    if (isSingleTripFrequencyWindow(end - start, departures.length, tripSpanMinutes, tripFrequencyRowCount)) return departures.slice(0, 1);
    return departures;
}

/**
 * Departure times for every frequencies.txt row of one trip, with overlapping
 * rows deduplicated (#711): a departure generated by a later row inside an
 * earlier row's window (file order) is dropped, so two window sets describing
 * the same hours (uga M Milledge has 07:00-18:30 twice) do not stack.
 * Back-to-back and after-midnight rows still expand in full. Rows on
 * different trips are never merged (terrebonne-parish 21's offset vehicles
 * are real combined service).
 */
export function expandTripFrequencyWindows(
    windows: readonly FrequencyWindow[],
    tripSpanMinutes?: number,
): number[] {
    const departures: number[] = [];
    // The earlier row (file order) wins wherever rows overlap: its departures are
    // kept whole, and a later row only fills hours no earlier row covers. Rows on
    // one trip describe one vehicle pattern, so overlapping rows are alternative
    // descriptions of the same hours, not extra buses.
    windows.forEach((window, index) => {
        for (const generated of expandFrequencyWindow(window, tripSpanMinutes, windows.length)) {
            if (windows.slice(0, index).some(prior => generated >= prior.start && generated < prior.end)) continue;
            if (!departures.includes(generated)) departures.push(generated);
        }
    });
    return departures;
}
