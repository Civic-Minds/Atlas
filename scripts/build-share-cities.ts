/**
 * Writes shared/shareCities.ts: the cities with a link-preview map picture (CIV-1175), with each one's downtown and
 * its simplified official boundary. Run after the area pages or their boundaries change:
 *
 *   npx tsx scripts/build-share-cities.ts
 *
 * Then capture any new city's picture with scripts/build-share-maps.ts.
 */
import { readFileSync, writeFileSync } from 'fs';

/** Area-page cities whose map is too empty to read as a picture: they keep the default picture (Ryan's review). */
export const SKIPPED_SHARE_CITIES: readonly string[] = ['kiryas-joel'];

/** Downtowns GeoNames gets wrong or lacks (towns under 50,000, or a name it files under another city). */
const DOWNTOWN_OVERRIDES: Record<string, [number, number]> = {
  'new-york': [40.7128, -74.006],
  blacksburg: [37.2296, -80.4139],
  bremerton: [47.5673, -122.6326],
  'kiryas-joel': [41.342, -74.1676],
  'san-luis-obispo': [35.2828, -120.6596],
  toronto: [43.6532, -79.3832],
  chicago: [41.8781, -87.6298],
  kitchener: [43.4516, -80.4925],
  // The network centres on Norfolk, not the Virginia Beach oceanfront.
  'virginia-beach': [36.8508, -76.2859],
};

/** About 1 km: plenty to tell neighbouring areas apart, and keeps the share function small. */
const SIMPLIFY_DEGREES = 0.01;

type Point = [number, number];

function simplify(points: Point[], eps: number): Point[] {
  if (points.length < 3) return points;
  const [x1, y1] = points[0];
  const [x2, y2] = points[points.length - 1];
  const dx = x2 - x1;
  const dy = y2 - y1;
  const len = Math.hypot(dx, dy);
  let dmax = 0;
  let index = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const [x, y] = points[i];
    const d = len ? Math.abs(dy * x - dx * y + x2 * y1 - y2 * x1) / len : Math.hypot(x - x1, y - y1);
    if (d > dmax) { dmax = d; index = i; }
  }
  if (dmax > eps) return [...simplify(points.slice(0, index + 1), eps).slice(0, -1), ...simplify(points.slice(index), eps)];
  return [points[0], points[points.length - 1]];
}

const round = (n: number, places: number) => Number(n.toFixed(places));

const index = JSON.parse(readFileSync('shared/data/area-index.json', 'utf8')) as Record<string, { page?: boolean; bbox: [number, number, number, number] }>;
const boundaries = JSON.parse(readFileSync('shared/data/area-boundaries.json', 'utf8')) as Record<string, { polygons: Point[][][] }>;
/** [name, lat, lon, country, region, population], largest first. */
const places = JSON.parse(readFileSync('shared/data/na-places.json', 'utf8')) as Array<[string, number, number, string, string, number]>;

const rows: string[] = [];
for (const slug of Object.keys(index).sort()) {
  if (!index[slug].page || SKIPPED_SHARE_CITIES.includes(slug)) continue;
  const area = JSON.parse(readFileSync(`config/areas/${slug}.json`, 'utf8')) as { name: string; cities: string[]; center: Point };
  const [s, w, n, e] = index[slug].bbox;
  const inBox = (p: (typeof places)[number]) => p[1] >= s && p[1] <= n && p[2] >= w && p[2] <= e;
  // The first listed city GeoNames knows in the area, else the area's largest place.
  const place = area.cities.map(c => places.find(p => p[0] === c && inBox(p))).find(Boolean) ?? places.find(inBox);
  const center: Point = DOWNTOWN_OVERRIDES[slug] ?? (place ? [round(place[1], 4), round(place[2], 4)] : area.center.map(v => round(v, 4)) as Point);
  if (!DOWNTOWN_OVERRIDES[slug] && (!place || !area.cities.includes(place[0]))) console.warn(`${slug}: downtown from ${place?.[0] ?? 'the area center'}; add an override if that's wrong`);
  const rings = boundaries[slug].polygons
    .map(polygon => simplify(polygon[0], SIMPLIFY_DEGREES).map(([x, y]) => [round(x, 3), round(y, 3)] as Point))
    .filter(ring => ring.length >= 4);
  rows.push(`  { slug: ${JSON.stringify(slug)}, name: ${JSON.stringify(area.name)}, center: ${JSON.stringify(center)}, bbox: ${JSON.stringify(index[slug].bbox)},\n    rings: ${JSON.stringify(rings)} },`);
}

const header = `/**
 * Cities with a ready-made link-preview map picture (public/assets/share/<slug>.jpg, made by
 * scripts/build-share-maps.ts), CIV-1175: the area-page cities (config/areas, page: true), minus ones whose map
 * is too empty to read as a picture. Generated by scripts/build-share-cities.ts; don't hand-edit.
 *
 * - center: the main city's downtown ([lat, lon], GeoNames via shared/data/na-places.json, a few set by hand):
 *   where its picture is framed, and the fallback distance check for points just outside every area.
 * - bbox: [south, west, north, east], as in shared/data/area-index.json.
 * - rings: the area's official boundary (shared/data/area-boundaries.json) simplified to about 1 km, as
 *   [lon, lat] rings, so a point is matched to the area it's really in, not just a bounding box.
 */

export interface ShareCity {
  slug: string;
  name: string;
  center: [number, number];
  bbox: [number, number, number, number];
  rings: Array<Array<[number, number]>>;
}

export const SHARE_CITIES: readonly ShareCity[] = [
`;
writeFileSync('shared/shareCities.ts', `${header}${rows.join('\n')}\n];\n`);
console.log(`Wrote shared/shareCities.ts: ${rows.length} cities`);
